"""Small SQLite/PostgreSQL compatibility layer for the DAVV event portal."""
import os
import sqlite3
from pathlib import Path

ROOT = Path(__file__).resolve().parent
DB_PATH = ROOT / "data" / "davv_events.db"


def _hybrid_row(cursor):
    if cursor.description is None:
        return tuple

    columns = [col.name for col in cursor.description]

    class HybridRow(dict):
        def __getitem__(self, key):
            if isinstance(key, int):
                key = columns[key]
            return super().__getitem__(key)

    def make_row(values):
        return HybridRow(zip(columns, values))

    return make_row



class PostgresCompat:
    def __init__(self, conn):
        self.conn = conn

    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc, tb):
        try:
            if exc_type:
                self.conn.rollback()
            else:
                self.conn.commit()
        finally:
            self.conn.close()
        return False

    def execute(self, sql, params=()):
        return self.conn.execute(sql.replace("?", "%s"), params)

    def executemany(self, sql, params):
        with self.conn.cursor() as cursor:
      	    cursor.executemany(sql.replace("?", "%s"), params)
      	    return cursor.rowcount


def database_url():
    return os.environ.get("DATABASE_URL", "").strip()


def db():
    url = database_url()
    if url:
        import psycopg
        from psycopg.rows import dict_row
        # Render may provide postgres://; psycopg expects postgresql://.
        if url.startswith("postgres://"):
            url = "postgresql://" + url[len("postgres://"):]
        if "sslmode=" not in url:
            url += ("&" if "?" in url else "?") + "sslmode=require"
        return PostgresCompat(psycopg.connect(url, row_factory=_hybrid_row))

    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys=ON")
    return conn


def is_integrity_error(exc):
    if isinstance(exc, sqlite3.IntegrityError):
        return True
    try:
        import psycopg
        return isinstance(exc, psycopg.IntegrityError)
    except ImportError:
        return False


def init_postgres_schema():
    """Create the production schema; safe to run on each app startup."""
    if not database_url():
        return
    schema = [
        """CREATE TABLE IF NOT EXISTS users (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            roll_number TEXT UNIQUE,
            name TEXT NOT NULL,
            contact_number TEXT NOT NULL DEFAULT '',
            email TEXT NOT NULL UNIQUE,
            password_hash TEXT NOT NULL,
            role TEXT NOT NULL CHECK(role IN ('student','admin')),
            must_change_password INTEGER NOT NULL DEFAULT 0,
            is_active INTEGER NOT NULL DEFAULT 1,
            created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        )""",
        "CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower_unique ON users (LOWER(email))",
        """CREATE TABLE IF NOT EXISTS events (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            title TEXT NOT NULL, category TEXT NOT NULL, description TEXT NOT NULL,
            event_date TEXT NOT NULL, event_time TEXT, venue TEXT NOT NULL,
            image_url TEXT, registration_deadline TEXT, capacity INTEGER,
            is_published INTEGER NOT NULL DEFAULT 0, created_by BIGINT,
            created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
            FOREIGN KEY(created_by) REFERENCES users(id)
        )""",
        """CREATE TABLE IF NOT EXISTS registrations (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            event_id BIGINT NOT NULL, user_id BIGINT NOT NULL,
            registered_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
            UNIQUE(event_id,user_id),
            FOREIGN KEY(event_id) REFERENCES events(id) ON DELETE CASCADE,
            FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
        )""",
        """CREATE TABLE IF NOT EXISTS notifications (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id BIGINT NOT NULL, event_id BIGINT, title TEXT NOT NULL,
            message TEXT NOT NULL, is_read INTEGER NOT NULL DEFAULT 0,
            created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
            FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
            FOREIGN KEY(event_id) REFERENCES events(id) ON DELETE SET NULL
        )""",
    ]
    with db() as conn:
        for statement in schema:
            conn.execute(statement)
